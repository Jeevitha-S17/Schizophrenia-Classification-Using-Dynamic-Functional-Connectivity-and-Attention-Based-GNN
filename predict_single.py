"""
predict_single.py

Standalone script: takes ONE connectivity-matrix image and produces:

  1. Dynamic Functional Connectivity   - the pseudo-dynamic window matrices
  2. Sliding Window Temporal Analysis   - which pseudo-window the model
                                          attended to most, via the
                                          transformer's sequence attention
  3. Attention-Based Brain Region ID    - which ROIs the GAT attended to
                                          most, via GATv2Conv attention
  4. Comparison: Dynamic vs Static      - both models' prediction +
                                          confidence side by side

Does NOT import train.py. Loads only the saved checkpoints + config.json.

*** APPROXIMATION NOTICE (see pseudo_dynamic.py) ***
There is no real time-series behind this single static image, so
"sliding window temporal analysis" here means the N synthetic bootstrap
windows generated by pseudo_dynamic.py, not literal sliding-window
analysis of a measured BOLD signal. All output text/labels say so
explicitly - keep that wording when you present these results.

Usage
-----
    python predict_single.py --image path/to/subject.png
    python predict_single.py --image path/to/subject.png --checkpoint_dir checkpoints --output_dir single_result

Tested against: Python 3.9.0
"""

import argparse
import json
import os

import numpy as np
import torch
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from torch_geometric.data import Batch

import config
from image_to_matrix import load_png_as_matrix
from pseudo_dynamic import generate_pseudo_windows
from graph_builder import matrix_to_graph, build_graph_sequence
from model import DynamicAttentionGNN, StaticGNN
from explain import (
    node_importance_from_attention,
    run_transformer_with_attention,
    window_importance_from_attention,
    top_k_indices,
)

CLASS_NAMES = {0: "Healthy", 1: "Schizophrenia"}


def parse_args():
    parser = argparse.ArgumentParser(description="Single-image DFC prediction + explanation")
    parser.add_argument("--image", type=str, required=True, help="Path to one connectivity-matrix image")
    parser.add_argument("--checkpoint_dir", type=str, default=config.CHECKPOINT_DIR)
    parser.add_argument("--output_dir", type=str, default="single_result")
    parser.add_argument("--top_k_rois", type=int, default=15)
    parser.add_argument("--device", type=str, default="cuda" if torch.cuda.is_available() else "cpu")
    return parser.parse_args()


def load_run_config(checkpoint_dir: str) -> dict:
    config_path = os.path.join(checkpoint_dir, "config.json")
    if not os.path.exists(config_path):
        raise FileNotFoundError(f"{config_path} not found. Run train.py first.")
    with open(config_path, "r") as f:
        return json.load(f)


def predict_static(model: StaticGNN, static_graph, device):
    """Run the static baseline and also extract GAT attention -> ROI importance."""
    batch = Batch.from_data_list([static_graph]).to(device)
    model.eval()
    with torch.no_grad():
        embedding, edge_index_out, alpha = model.spatial_encoder(
            batch.x, batch.edge_index, batch.edge_attr, batch.batch, return_attention=True
        )
        logits = model.classifier(embedding)
        probs = torch.softmax(logits, dim=-1)[0]
        roi_importance = node_importance_from_attention(edge_index_out, alpha, num_nodes=batch.x.size(0))
    return probs.cpu().numpy(), roi_importance.cpu().numpy()


def predict_dynamic(model: DynamicAttentionGNN, window_graphs, device):
    """
    Run the pseudo-dynamic model and extract both:
      - per-window ROI attention (spatial GAT attention, averaged over windows)
      - per-window temporal importance (transformer sequence attention)
    """
    model.eval()
    n_windows = len(window_graphs)

    big_batch = Batch.from_data_list(window_graphs).to(device)
    with torch.no_grad():
        window_embeddings, edge_index_out, alpha = model.spatial_encoder(
            big_batch.x, big_batch.edge_index, big_batch.edge_attr, big_batch.batch, return_attention=True
        )
        # window_embeddings: [n_windows, hidden_dim] (batch_size=1 subject)
        roi_importance_all_nodes = node_importance_from_attention(
            edge_index_out, alpha, num_nodes=big_batch.x.size(0)
        )
        num_rois = config.NUM_ROIS
        # Nodes are concatenated window-by-window (n_windows graphs of num_rois
        # nodes each, in order) since this call processes exactly one subject.
        roi_importance_per_window = roi_importance_all_nodes.view(n_windows, num_rois)
        roi_importance_avg = roi_importance_per_window.mean(dim=0)  # [num_rois]

        sequence_input = window_embeddings.unsqueeze(0)  # [1, n_windows, hidden_dim]
        attended, attn_weights_per_layer = run_transformer_with_attention(
            model.sequence_attention, sequence_input
        )
        window_importance = window_importance_from_attention(attn_weights_per_layer)  # [n_windows]

        subject_embedding = attended.mean(dim=1)  # [1, hidden_dim]
        logits = model.classifier(subject_embedding)
        probs = torch.softmax(logits, dim=-1)[0]

    return (
        probs.cpu().numpy(),
        roi_importance_avg.cpu().numpy(),
        roi_importance_per_window.cpu().numpy(),
        window_importance.cpu().numpy(),
    )


def plot_dfc_window_matrices(windows: np.ndarray, out_path: str, max_windows_shown: int = 6):
    """Visualize the first few pseudo-dynamic window connectivity matrices."""
    n_show = min(max_windows_shown, windows.shape[0])
    fig, axes = plt.subplots(1, n_show, figsize=(3 * n_show, 3.2))
    if n_show == 1:
        axes = [axes]
    for i in range(n_show):
        im = axes[i].imshow(windows[i], cmap="coolwarm", vmin=-1, vmax=1)
        axes[i].set_title(f"Window {i + 1}", fontsize=10)
        axes[i].set_xticks([])
        axes[i].set_yticks([])
    fig.suptitle("Pseudo-dynamic connectivity matrices (bootstrap windows, not measured time-series)", fontsize=10)
    fig.colorbar(im, ax=axes, shrink=0.7, label="connectivity strength")
    fig.savefig(out_path, bbox_inches="tight")
    plt.close(fig)


def plot_window_temporal_attention(window_importance: np.ndarray, out_path: str):
    fig, ax = plt.subplots(figsize=(8, 3.5))
    x = np.arange(1, len(window_importance) + 1)
    ax.bar(x, window_importance, color="#4C72B0")
    ax.set_xlabel("Pseudo-window index")
    ax.set_ylabel("Sequence attention weight")
    ax.set_title("Sliding-window temporal analysis: attention per window")
    ax.set_xticks(x)
    fig.tight_layout()
    fig.savefig(out_path)
    plt.close(fig)


def plot_top_rois(top_rois: list, title: str, out_path: str):
    labels = [f"ROI_{idx}" for idx, _ in top_rois]
    scores = [score for _, score in top_rois]
    fig, ax = plt.subplots(figsize=(7, max(3, 0.3 * len(labels))))
    y_pos = np.arange(len(labels))
    ax.barh(y_pos, scores, color="#55A868")
    ax.set_yticks(y_pos)
    ax.set_yticklabels(labels)
    ax.invert_yaxis()
    ax.set_xlabel("Attention-based importance score")
    ax.set_title(title)
    fig.tight_layout()
    fig.savefig(out_path)
    plt.close(fig)


def plot_static_vs_dynamic(static_probs: np.ndarray, dynamic_probs: np.ndarray, out_path: str):
    fig, ax = plt.subplots(figsize=(6, 4))
    labels = ["Healthy", "Schizophrenia"]
    x = np.arange(len(labels))
    width = 0.35
    ax.bar(x - width / 2, static_probs, width, label="Static model", color="#DD8452")
    ax.bar(x + width / 2, dynamic_probs, width, label="Pseudo-dynamic model", color="#4C72B0")
    ax.set_xticks(x)
    ax.set_xticklabels(labels)
    ax.set_ylabel("Predicted probability")
    ax.set_ylim(0, 1)
    ax.set_title("Static vs pseudo-dynamic connectivity: prediction comparison")
    ax.legend()
    fig.tight_layout()
    fig.savefig(out_path)
    plt.close(fig)


def main():
    args = parse_args()
    device = torch.device(args.device)
    os.makedirs(args.output_dir, exist_ok=True)

    run_config = load_run_config(args.checkpoint_dir)

    static_model = StaticGNN(hidden_dim=run_config["hidden_dim"], dropout=run_config["dropout"]).to(device)
    static_model.load_state_dict(
        torch.load(os.path.join(args.checkpoint_dir, "best_static_model.pt"), map_location=device)
    )

    dynamic_model = DynamicAttentionGNN(hidden_dim=run_config["hidden_dim"], dropout=run_config["dropout"]).to(device)
    dynamic_model.load_state_dict(
        torch.load(os.path.join(args.checkpoint_dir, "best_dynamic_model.pt"), map_location=device)
    )

    # --- 1. Load image -> static connectivity matrix -----------------------
    static_matrix = load_png_as_matrix(args.image, num_rois=config.NUM_ROIS, use_cache=False)

    # --- 2. Sliding-window temporal analysis (pseudo-dynamic windows) ------
    windows = generate_pseudo_windows(static_matrix, subject_salt=0)  # [N_WINDOWS, R, R]

    # --- 3. Build graphs -----------------------------------------------------
    static_graph = matrix_to_graph(static_matrix)
    window_graphs = build_graph_sequence(windows)

    # --- 4. Run both models + extract attention -----------------------------
    static_probs, static_roi_importance = predict_static(static_model, static_graph, device)
    dynamic_probs, dynamic_roi_importance, roi_importance_per_window, window_importance = predict_dynamic(
        dynamic_model, window_graphs, device
    )

    static_pred = int(np.argmax(static_probs))
    dynamic_pred = int(np.argmax(dynamic_probs))

    # --- 5. Attention-based brain region identification ----------------------
    top_rois_static = top_k_indices(torch.tensor(static_roi_importance), args.top_k_rois)
    top_rois_dynamic = top_k_indices(torch.tensor(dynamic_roi_importance), args.top_k_rois)

    # --- 6. Save visualizations -----------------------------------------------
    plot_dfc_window_matrices(windows, os.path.join(args.output_dir, "dynamic_functional_connectivity.png"))
    plot_window_temporal_attention(window_importance, os.path.join(args.output_dir, "sliding_window_temporal_analysis.png"))
    plot_top_rois(
        top_rois_dynamic, "Attention-based brain region identification (pseudo-dynamic model)",
        os.path.join(args.output_dir, "attention_brain_regions_dynamic.png"),
    )
    plot_top_rois(
        top_rois_static, "Attention-based brain region identification (static model)",
        os.path.join(args.output_dir, "attention_brain_regions_static.png"),
    )
    plot_static_vs_dynamic(static_probs, dynamic_probs, os.path.join(args.output_dir, "static_vs_dynamic_comparison.png"))

    # --- 7. Console summary -----------------------------------------------------
    print("=" * 70)
    print(f"Image: {args.image}")
    print("=" * 70)
    print("\n--- COMPARISON: DYNAMIC vs STATIC CONNECTIVITY METHODS ---")
    print(f"Static model      -> {CLASS_NAMES[static_pred]:15s}  "
          f"(confidence: HC={static_probs[0]:.3f}, SZ={static_probs[1]:.3f})")
    print(f"Pseudo-dynamic     -> {CLASS_NAMES[dynamic_pred]:15s}  "
          f"(confidence: HC={dynamic_probs[0]:.3f}, SZ={dynamic_probs[1]:.3f})")
    if static_pred == dynamic_pred:
        print("Both models agree.")
    else:
        print("Models DISAGREE - inspect both confidence scores before trusting either.")

    print(f"\n--- SLIDING WINDOW TEMPORAL ANALYSIS ({config.N_WINDOWS} pseudo-windows) ---")
    most_attended_window = int(np.argmax(window_importance)) + 1
    print(f"Most-attended pseudo-window: {most_attended_window} "
          f"(attention weight: {window_importance.max():.4f})")
    print("Per-window attention weights:", np.round(window_importance, 4).tolist())

    print(f"\n--- ATTENTION-BASED BRAIN REGION IDENTIFICATION (top {args.top_k_rois}) ---")
    print("Pseudo-dynamic model top ROIs (index: score):")
    for idx, score in top_rois_dynamic:
        print(f"  ROI_{idx}: {score:.4f}")

    print("\nNOTE: 'ROI_<index>' refers to node position in the NUM_ROIS x NUM_ROIS")
    print("matrix, not a named anatomical atlas region - map these indices to real")
    print("region names only if you know which atlas your original PNGs used.")
    print("\nNOTE: the pseudo-dynamic windows above are a statistically simulated")
    print("bootstrap approximation of the single static matrix, not a measured")
    print("BOLD time-series. Report this explicitly alongside these results.")

    # --- 8. Save a machine-readable summary too --------------------------------
    summary = {
        "image": args.image,
        "static_prediction": CLASS_NAMES[static_pred],
        "static_confidence": {"Healthy": float(static_probs[0]), "Schizophrenia": float(static_probs[1])},
        "dynamic_prediction": CLASS_NAMES[dynamic_pred],
        "dynamic_confidence": {"Healthy": float(dynamic_probs[0]), "Schizophrenia": float(dynamic_probs[1])},
        "models_agree": bool(static_pred == dynamic_pred),
        "n_pseudo_windows": config.N_WINDOWS,
        "window_temporal_attention": window_importance.tolist(),
        "most_attended_window": most_attended_window,
        "top_rois_dynamic": [{"roi_index": idx, "score": score} for idx, score in top_rois_dynamic],
        "top_rois_static": [{"roi_index": idx, "score": score} for idx, score in top_rois_static],
    }
    with open(os.path.join(args.output_dir, "prediction_summary.json"), "w") as f:
        json.dump(summary, f, indent=2)

    print(f"\nAll outputs written to: {args.output_dir}/")


if __name__ == "__main__":
    main()
